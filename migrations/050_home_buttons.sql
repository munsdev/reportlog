-- THE FRONT PAGE'S BUTTONS, IN THE OPERATOR'S ORDER.
--
-- The front page had one accent button, "Submit a Report", which led to a
-- page whose whole job was to ask which logbook. So on a deployment with
-- three logbooks the front page named none of them and the real choice was
-- one click further in — while LISTS, which arrived later, each got their
-- own button right there. Two formats, two completely different front
-- doors, for no reason either of them could explain.
--
-- So there is one list of buttons and a logbook is in it the way a list
-- is.
--
-- WHAT IS STORED IS AN ORDER AND NOTHING ELSE. An array of
-- `{"kind":"logbook","ref":"polling-places"}` objects, in the order they
-- appear down the page.
--
-- NO LABELS AND NO COLOURS IN HERE, and both omissions are deliberate.
--
--   A LABEL would let an operator relabel somebody else's front door.
--   public/js/feedback.js already states the rule for the on-page editor:
--   the nav and the headings the software owns are not editable, because an
--   operator who could rewrite "Submit a report" could make the form lie
--   about what it does. A logbook button wears the logbook's own title,
--   which the operator edits where the logbook is edited — one name for one
--   thing, in one place.
--
--   A COLOUR would be a second way to say the same thing as the order, and
--   the two would disagree. One screen has one primary action: the first
--   button in this list is the accent and the rest are secondary, so the
--   order IS the emphasis. Three accent buttons is no accent at all, and a
--   per-button colour picker is a setting whose wrong value cannot be
--   caught by anything — it just quietly flattens the hierarchy the
--   palette exists to create.
--
-- NULL MEANS NOBODY HAS ARRANGED IT, which is not the same as an empty
-- list. NULL gets the shipped arrangement; `[]` is an operator who removed
-- every button and must get what they asked for. Same tri-state care as
-- `public_archive_enabled` and for the same reason.
--
-- AN ENTRY NAMING SOMETHING THAT IS GONE IS SKIPPED, AND ANYTHING MISSING
-- IS APPENDED. Both halves matter and the second one more: without it, a
-- logbook created after somebody arranged the page would never appear on
-- it, and the operator would have no way to know that arranging the page
-- once had quietly opted them out of every logbook they made afterwards.
-- src/homeButtons.js resolves both.
--
-- NOTHING HERE IS HASHED. It is the front page's layout.

ALTER TABLE site_settings ADD COLUMN home_buttons jsonb;
